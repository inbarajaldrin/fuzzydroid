"""Reproducible setup and user-level loader; no edits to KiCad application files."""

from __future__ import annotations

import hashlib
import json
import os
import shutil
import subprocess
import tarfile
import urllib.request
from datetime import UTC, datetime
from pathlib import Path

from fuzzydroid_kicad.platform import default_venv_path

from . import __version__
from .paths import cli_path, python_path, state_path
from .paths import plugin_dir as default_plugin_dir

BINDINGS = "8cdeb8964597968b11b2176ee288ccf1811d1633"
PROTOS = "17d01cb65d379cd14a16c8ca141ab1d857c562a5"
MARKER = "# Generated by fuzzydroid-kicad; rerun /kicad:setup after updates."
ARCHIVE_HASHES = {
    "kicad-python": "b2432b9e58e4cf762c820e3722b7917ea6a4515d48421b1be514d2c01c1cbc77",
    "kicad": "d0b1bfdb66a9f1c6e5330390939aa38bac6c59c14562c7dd309bd5cb2d4b1e79",
}


def digest(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def run(*args, env=None):
    return subprocess.run(
        [str(arg) for arg in args], check=True, capture_output=True, text=True, env=env
    )


def extract(archive: Path, destination: Path):
    with tarfile.open(archive) as stream:
        for member in stream.getmembers():
            target = (destination / member.name).resolve()
            if not target.is_relative_to(destination.resolve()) or member.issym() or member.islnk():
                raise ValueError("Unsafe archive member: " + member.name)
        stream.extractall(destination)


def stable_bindings(python: Path):
    """Build official stable bindings without cloning KiCad's multi-GB history."""
    vendor = state_path().parent / "kicad-vendor"
    vendor.mkdir(parents=True, exist_ok=True)
    for project, ref, suffix in [
        ("kicad-python", BINDINGS, ""),
        ("kicad", PROTOS, "?path=api/proto"),
    ]:
        archive = vendor / f"{project}-{ref}.tar.gz"
        if not archive.exists():
            url = f"https://gitlab.com/kicad/code/{project}/-/archive/{ref}/{project}-{ref}.tar.gz{suffix}"
            temporary = archive.with_suffix(".download")
            try:
                urllib.request.urlretrieve(url, temporary)
                temporary.replace(archive)
            finally:
                temporary.unlink(missing_ok=True)
        if digest(archive) != ARCHIVE_HASHES[project]:
            raise ValueError("Binding archive checksum mismatch: " + str(archive))
        extract(archive, vendor)
    source = vendor / f"kicad-python-{BINDINGS}"
    shutil.copytree(
        vendor / f"kicad-{PROTOS}-api-proto/api", source / "kicad/api", dirs_exist_ok=True
    )
    run("uv", "pip", "install", "--python", python, "protoc-wheel-0==29.3")
    env = dict(os.environ)
    env["PATH"] = str(python.parent) + os.pathsep + env.get("PATH", "")
    run("uv", "pip", "install", "--python", python, source, env=env)


def install(
    plugin_root: Path,
    kicad_cli: str | None = None,
    plugin_dir: Path | None = None,
    native: bool = True,
) -> dict:
    root = plugin_root.expanduser().resolve()
    package = root / "lib/fuzzydroid_kicad"
    if not (package / "pyproject.toml").is_file():
        raise ValueError("Plugin root does not contain lib/fuzzydroid_kicad/pyproject.toml")
    if not shutil.which("uv"):
        raise RuntimeError("Install uv, then rerun /kicad:setup")
    cli = cli_path(kicad_cli)
    version = run(cli, "version").stdout.strip()
    major = int(version.split(".")[0])
    if major < 9:
        raise ValueError("Official IPC requires KiCad 9 or newer")
    if native and major != 10:
        raise ValueError(
            "The embedded backend is qualified for KiCad 10; pass --no-native for IPC only"
        )
    destination = (plugin_dir or default_plugin_dir(major)).expanduser().resolve()
    loader = destination / "fzd_kicad_loader.py"
    if loader.exists() and not loader.read_text(encoding="utf-8").startswith(MARKER):
        raise FileExistsError("Refusing to overwrite an unrelated plugin loader: " + str(loader))
    python = python_path()
    if not python.exists():
        run("uv", "venv", default_venv_path(), "--python", "3.11")
    run("uv", "pip", "install", "--python", python, "--editable", package)
    if major == 10:
        stable_bindings(python)
    loader_text = (
        MARKER
        + "\nimport sys\n"
        + f"sys.path.insert(0, {str(package)!r})\n"
        + "from fuzzydroid_kicad.bridge import start\nstart()\n"
    )
    if native:
        destination.mkdir(parents=True, exist_ok=True)
        loader.write_bytes(loader_text.encode())
    elif loader.exists():
        loader.unlink()
    state = {
        "venv_path": str(default_venv_path()),
        "plugin_version": __version__,
        "pyproject_hash": digest(package / "pyproject.toml"),
        "install_timestamp": datetime.now(UTC).isoformat(),
        "python_version": run(python, "--version").stdout.strip(),
        "plugin_root": str(root),
        "kicad_cli": str(cli),
        "kicad_version": version,
        "native_enabled": native,
        "loader_path": str(loader),
        "loader_hash": hashlib.sha256(loader_text.encode()).hexdigest() if native else "",
    }
    target = state_path()
    target.parent.mkdir(parents=True, exist_ok=True)
    # Values are strings/bools only; JSON strings are also valid TOML strings here.
    text = (
        "\n".join(
            key + " = " + (str(value).lower() if isinstance(value, bool) else json.dumps(value))
            for key, value in state.items()
        )
        + "\n"
    )
    temporary = target.with_suffix(".tmp")
    temporary.write_text(text)
    temporary.replace(target)
    return {
        "installed": True,
        "state": str(target),
        "native_enabled": native,
        "restart_required": native,
        "next": "Restart PCB Editor to load the bridge. Enable API in Preferences > Plugins for IPC. Run /kicad:doctor.",
    }
